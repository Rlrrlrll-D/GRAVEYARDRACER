-- Разжать маску в буфер RGBA: белый цвет + альфа по силуэту. Цвет даёт ImageColor3,
-- поэтому одной картинки хватает на плашки любого цвета.
local function decode(w: number, h: number, data: string): buffer
	local s = string.gsub(data, "\n", "")
	local buf = buffer.create(w * h * 4)
	local at = 0
	for i = 1, #s, 2 do
		local level = string.byte(s, i) - 48 -- '0' = 48
		local alpha = level * 255 // 7
		local count = COUNT[string.byte(s, i + 1)] or 1
		for _ = 1, count do
			buffer.writeu8(buf, at, 255)
			buffer.writeu8(buf, at + 1, 255)
			buffer.writeu8(buf, at + 2, 255)
			buffer.writeu8(buf, at + 3, alpha)
			at += 4
		end
	end
	return buf
end

-- Картинки строим лениво и по одной на форму: их три на весь интерфейс, а
-- ImageLabel'ов, которые на них ссылаются, сколько угодно — цвет у каждого свой.
local built: { [number]: Content? } = {}
local tried: { [number]: boolean } = {}

local function image(slot: number): Content?
	if tried[slot] then
		return built[slot]
	end
	tried[slot] = true

	local shape = SHAPES[slot]
	local w, h, data = shape[1] :: number, shape[2] :: number, shape[3] :: string

	local ok, img = pcall(function()
		return AssetService:CreateEditableImage({ Size = Vector2.new(w, h) })
	end)
	if not ok or not img then
		return nil
	end

	local written = pcall(function()
		img:WritePixelsBuffer(Vector2.zero, Vector2.new(w, h), decode(w, h, data))
	end)
	if not written then
		-- Настройка Security в Experience Settings выключена: плашки нарисуются
		-- запасными прямоугольниками, интерфейс остаётся рабочим.
		return nil
	end

	built[slot] = Content.fromObject(img)
	return built[slot]
end

-- // Сборка плашки ------------------------------------------------------------
-- Мазок кладётся ВНУТРЬ контейнера, а не является им сам, по двум причинам:
-- поворот на 180° перевернул бы вместе с плашкой и надпись, а рваные края оставили
-- бы мёртвые зоны для мыши. Контейнер прямоугольный и невидимый — он ловит клик,
-- мазок только красит.
local function brushInto(parent: GuiObject, slot: number, color: Color3, turn: boolean)
	local content = image(slot)
	if content then
		local img = Instance.new("ImageLabel")
		img.Name = "Brush"
		img.BackgroundTransparency = 1
		img.Size = UDim2.fromScale(1, 1)
		img.ImageContent = content
		img.ImageColor3 = color
		img.ScaleType = Enum.ScaleType.Stretch
		img.Rotation = if turn then 180 else 0
		img.ZIndex = parent.ZIndex
		img.Parent = parent
		return
	end
	local f = Instance.new("Frame")
	f.Name = "Brush"
	f.Size = UDim2.fromScale(1, 1)
	f.BackgroundColor3 = color
	f.BorderSizePixel = 0
	f.ZIndex = parent.ZIndex
	local c = Instance.new("UICorner")
	c.CornerRadius = UDim.new(0, 8)
	c.Parent = f
	f.Parent = parent
end

-- Форма по порядковому номеру: два мазка × два поворота, подряд не повторяются.
local function shapeFor(index: number): (number, boolean)
	local i = (index - 1) % 4
	return (i % 2) + 1, i >= 2
end

-- Покрасить мазок, не трогая запомненный цвет: этим живёт подсветка наведения.
local function paint(plate: GuiObject, color: Color3)
	local brush = plate:FindFirstChild("Brush")
	if brush and brush:IsA("ImageLabel") then
		brush.ImageColor3 = color
	elseif brush and brush:IsA("Frame") then
		brush.BackgroundColor3 = color
	end
end

-- Перекрасить плашку насовсем (PLAY меняет цвет по готовности).
function PlateArt.tint(plate: GuiObject, color: Color3)
	plate:SetAttribute("BaseColor", color)
	paint(plate, color)
end

-- Наведение мыши подсвечивает мазок. AutoButtonColor тут бесполезен: фон
-- контейнера прозрачный, движку нечего затемнять — красим сам мазок.
local function hoverable(plate: GuiObject)
	local function shade(k: number)
		local base = plate:GetAttribute("BaseColor")
		if typeof(base) == "Color3" then
			paint(plate, (base :: Color3):Lerp(Color3.new(1, 1, 1), k))
		end
	end
	plate.MouseEnter:Connect(function()
		shade(0.18)
	end)
	plate.MouseLeave:Connect(function()
		shade(0)
	end)
end

-- Кликаемая плашка. index — номер по порядку в столбце, от него зависит форма.
function PlateArt.button(index: number, color: Color3): TextButton
	local b = Instance.new("TextButton")
	b.Name = "Plate"
	b.BackgroundTransparency = 1
	b.Text = ""
	b.AutoButtonColor = false
	b:SetAttribute("BaseColor", color)
	local slot, turn = shapeFor(index)
	brushInto(b, slot, color, turn)
	hoverable(b)
	return b
end

-- Некликаемая плашка: строка ростера, ярлык.
function PlateArt.plate(index: number, color: Color3): Frame
	local f = Instance.new("Frame")
	f.Name = "Plate"
	f.BackgroundTransparency = 1
	f:SetAttribute("BaseColor", color)
	local slot, turn = shapeFor(index)
	brushInto(f, slot, color, turn)
	return f
end

-- Сплошная подложка панели: плотное нутро, рваные края.
function PlateArt.backdrop(color: Color3): Frame
	local f = Instance.new("Frame")
	f.Name = "Backdrop"
	f.BackgroundTransparency = 1
	f:SetAttribute("BaseColor", color)
	brushInto(f, 3, color, false)
	return f
end

-- Надпись поверх плашки. Поле по бокам съедает рваные концы мазка: в них текст
-- тонет. Узкой плашке (тумблер ON/OFF) двадцати пикселей поля много — там pad свой.
function PlateArt.caption(plate: GuiObject, text: string, color: Color3?, pad: number?): TextLabel
	local p = pad or 20
	local l = Instance.new("TextLabel")
	l.Name = "Caption"
	l.BackgroundTransparency = 1
	l.Size = UDim2.new(1, -2 * p, 1, -14)
	l.Position = UDim2.fromOffset(p, 7)
	l.Text = text
	l.TextScaled = true
	l.Font = UITheme.Font
	local ink = color or UITheme.Ink
	l.TextColor3 = ink
	-- ОБВОДКА ТОЛЬКО ПОД СВЕТЛЫЙ ТЕКСТ. На костяной плашке надпись тёмная, и тёмная
	-- же обводка вокруг неё утолщала буквы до нечитаемой каши. Светлый текст обводку
	-- держит — он лежит на тёмном мазке, и она отделяет его от фона.
	l.TextStrokeColor3 = UITheme.Shadow
	l.TextStrokeTransparency = if (0.299 * ink.R + 0.587 * ink.G + 0.114 * ink.B) > 0.5 then 0.35 else 1
	l.ZIndex = plate.ZIndex + 1
	l.Parent = plate
	return l
end

return PlateArt
